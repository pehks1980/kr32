from nodes import (
    TranslationUnit,
    Function,
    Print,
    Return,
    IntLiteral,
)


# Raised when the AST contains something that our
# current KRCC code generator cannot translate.
class CodegenError(Exception):
    pass


class CodeGenerator:
    def __init__(self):
        # Assembly instructions are accumulated here.
        self.output = []
        self.string_data = []

    def emit(self, instruction):
        # Add one line to the generated assembly.
        self.output.append(instruction)

    def generate(self, ast):
        """
        Entry point of the code generator.

        Accepts a TranslationUnit AST and returns
        a complete KR32 assembly program.
        """

        # Start with a clean output buffer.
        self.output = []
        self.string_data = []

        if not isinstance(ast, TranslationUnit):
            raise CodegenError(
                "Expected a TranslationUnit AST"
            )

        # Our initial compiler supports exactly one function.
        if len(ast.functions) != 1:
            raise CodegenError(
                "Currently only one function is supported"
            )

        function = ast.functions[0]

        # For now, we only support main().
        if function.name != "main":
            raise CodegenError(
                "Currently only main() is supported"
            )

        if function.return_type != "int":
            raise CodegenError(
                "Only int return type is supported"
            )

        # The assembly origin follows the existing KR32
        # executable layout convention.
        self.emit("; Generated by KRCC")
        self.emit("")
        self.emit(".ORG 0x43000")
        self.emit(".EQU SYS_EXIT, 1")
        self.emit(".EQU SYS_WRITE, 4")
        self.emit("")

        # The executable begins here.
        self.emit("program_start:")

        # Generate the function body.
        self.generate_function(function)
        self.output.extend(self.string_data)

        # Return the complete assembly source.
        return "\n".join(self.output) + "\n"

    def generate_function(self, function):
        """
        Generate instructions for a function body.

        Currently, statements are generated in source order.
        """

        for statement in function.body:
            self.generate_statement(statement)

    def generate_statement(self, statement):
        """
        Dispatch generation according to AST node type.

        As we add more C statements, we will extend this method.
        """

        if isinstance(statement, Return):
            self.generate_return(statement)
            return

        if isinstance(statement, Print):
            self.generate_print(statement)
            return

        raise CodegenError(
            f"Unsupported statement: {type(statement).__name__}"
        )

    def generate_print(self, statement):
        value = statement.value.value
        if not value.isascii():
            raise CodegenError("printf string literals must contain ASCII text")

        label = f"printf_string_{len(self.string_data)}"
        self.emit("    LI R1 1")
        self.emit(f"    LI R2 {label}")
        self.emit(f"    LI R3 {len(value)}")
        self.emit("    SVC SYS_WRITE")
        self.string_data.extend(
            [
                f"{label}:",
                f"    .ASCIIZ {value!r}",
            ]
        )

    def generate_return(self, statement):
        """
        Generate code for:

            return INTEGER;

        Our temporary convention:
            R1 = return value
            SYS_EXIT = terminate the current user process
        """

        value = statement.value

        if not isinstance(value, IntLiteral):
            raise CodegenError(
                "Currently return requires an integer literal"
            )

        # Load the return value into R1.
        self.emit(f"    LI R1 {value.value}")

        self.emit("    SVC SYS_EXIT")
