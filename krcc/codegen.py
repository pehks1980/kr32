from nodes import (
    TranslationUnit,
    Function,
    Print,
    Return,
    IntLiteral,
    VariableDeclaration,
    Variable,
    Assignment,
    BinaryExpression,
)

# ================================================================
# KR32 ABI v1.0 — REGISTER AND CALLING CONVENTION
# ================================================================
#
# REGISTER ROLES:
#
#   R0        = Hardwired ZERO register
#
#   R1-R4     = Argument registers (arg0..arg3)
#               Also used for return values (R1-R4)
#               Caller-saved / volatile
#
#   R5-R11    = General-purpose working registers
#               Callee-saved / preserved
#
#   R12       = General-purpose working register
#               Callee-saved / preserved
#
#   R13       = SP (Stack Pointer)
#   R14       = FP (Frame Pointer)
#   R15       = LR (Link Register)
#
# CALLING CONVENTION:
#
#   1. Arguments 0-3 are passed in R1-R4.
#   2. Additional arguments are passed on the stack.
#   3. Return values are returned in R1-R4.
#   4. R1-R4 may be modified by the callee.
#   5. R5-R12 must be preserved by the callee.
#      Save only registers actually modified.
#   6. SP must be restored before returning.
#   7. FP must be preserved by the callee.
#   8. LR must be preserved across nested function calls.
#      A leaf function need not save LR if it does not overwrite it.
#   9. Stack grows downward (towards lower addresses).
#  10. PUSH: SP = SP - 4, then MEM[SP] = value.
#  11. POP:  value = MEM[SP], then SP = SP + 4.
#
# VOLATILE REGISTERS:
#   R1-R4
#
# NON-VOLATILE REGISTERS:
#   R5-R12, R14
#
# SPECIAL:
#   R0 = ZERO, R13 = SP, R15 = LR
#
# ================================================================

# Raised when the AST contains something that our
# current KRCC code generator cannot translate.
class CodegenError(Exception):
    pass


class CodeGenerator:
    def __init__(self):
        # Assembly instructions are accumulated here.
        self.output = []
        self.string_data = []

    def emit(self, instruction):
        # Add one line to the generated assembly.
        self.output.append(instruction)

    
    def generate(self, ast):
        self.output = []
        self.string_data = []

        if not isinstance(ast, TranslationUnit):
            raise CodegenError("Expected a TranslationUnit AST")

        if len(ast.functions) != 1:
            raise CodegenError("Currently only one function is supported")

        function = ast.functions[0]

        if function.name != "main":
            raise CodegenError("Currently only main() is supported")

        if function.return_type != "int":
            raise CodegenError("Only int return type is supported")

        self.emit("; Generated by KRCC")
        self.emit("")
        self.emit(".ORG 0x00043000")
        self.emit(".EQU SYS_EXIT, 1")
        self.emit(".EQU SYS_SLEEP, 15")
        self.emit(".EQU SYS_WRITE, 4")
        self.emit("")
        self.emit("_start:")
        self.emit("    BL main")
        self.emit("    PUSH R1")
        self.emit("    LI R1 1")
        self.emit("    SVC SYS_SLEEP")
        self.emit("    POP R1")
        self.emit("    SVC SYS_EXIT")
        self.emit("")

        self.generate_function(function)

        self.output.extend(self.string_data)
        return "\n".join(self.output) + "\n"


    def generate_function(self, function):
        """
                Standard KR32 function frame.
        
                Entry:
                    SP = valid stack pointer supplied by caller
                    LR = return address
        
                Frame:
                    [FP + 0] = saved FP
                    [FP + 4] = saved LR
                    [FP - 4] = local variable 1
                    [FP - 8] = local variable 2
                    ...
                """
        self.current_function = function
        self.emit(f"{function.name}:")
        self.emit("    PUSH LR")
        self.emit("    PUSH FP")
        self.emit("    MOV FP SP")
        self.emit(f"    SUB SP SP {function.frame_size}")

        self.return_generated = False

        for statement in function.body:
            self.generate_statement(statement)

        if not self.return_generated:
            self.emit("    LI R1 0")
            self.emit("    MOV SP FP")
            self.emit("    POP FP")
            self.emit("    POP LR")
            self.emit("    RET")

    def generate_epilogue(self):
        self.emit("    MOV SP FP")
        self.emit("    POP FP")
        self.emit("    POP LR")
        self.emit("    RET")

    def generate_statement(self, statement):

        if isinstance(statement, VariableDeclaration):
            # Storage was allocated in the function frame.
            # No runtime instruction is required here.
            return

        if isinstance(statement, Assignment):
            self.generate_assignment(statement)
            return

        if isinstance(statement, Return):
            self.generate_return(statement)
            return

        if isinstance(statement, Print):
            self.generate_print(statement)
            return

        raise CodegenError(
            f"Unsupported statement: {type(statement).__name__}"
        )

    def generate_assignment(self, statement):
        if not hasattr(statement, "symbol"):
            raise CodegenError(
                f"Assignment '{statement.name}' has no semantic symbol"
            )

        symbol = statement.symbol
        offset = symbol.stack_offset

        self.generate_expression(statement.value, "R1")
        self.emit(f"    STW R1 [FP {offset:+d}]")

    def generate_expression(self, expression, target="R1"):

        # print(
        #     "EXPR DEBUG:",
        #     repr(expression),
        #     type(expression),
        #     isinstance(expression, Variable),
        #     isinstance(expression, IntLiteral)
        # )

        if isinstance(expression, IntLiteral):
            self.emit(f"    LI {target} {expression.value}")
            return

        if isinstance(expression, Variable):
            if not hasattr(expression, "symbol"):
                raise CodegenError(
                    f"Variable '{expression.name}' has no semantic symbol"
                )

            offset = expression.symbol.stack_offset
            self.emit(f"    LDW {target} [FP {offset:+d}]")
            return

        if isinstance(expression, BinaryExpression):

            if expression.operator != "+":
                raise CodegenError(
                    f"Unsupported binary operator: {expression.operator}"
                )

            # Initial implementation: variable/literal operands.
            self.generate_expression(expression.left, "R1")
            self.generate_expression(expression.right, "R2")

            self.emit("    ADD R1 R1 R2")

            if target != "R1":
                self.emit(f"    MOV {target} R1")

            return

        raise CodegenError(
            f"Unsupported expression: {type(expression).__name__}"
        )


    def generate_return(self, statement):
        self.generate_expression(statement.value)

        self.emit("    MOV SP FP")
        self.emit("    POP FP")
        self.emit("    POP LR")
        self.emit("    RET")

        self.return_generated = True


    def generate_print(self, statement):
        if statement.arguments:
            raise CodegenError("printf format arguments are not yet supported")

        value = statement.format_string.value
        if not value.isascii():
            raise CodegenError("printf string literals must contain ASCII text")

        label = f"printf_string_{len(self.string_data)}"
        self.emit("    LI R1 1")
        self.emit(f"    LI R2 {label}")
        self.emit(f"    LI R3 {len(value)}")
        self.emit("    SVC SYS_WRITE")
        self.string_data.extend(
            [
                f"{label}:",
                f"    .ASCIIZ {value!r}",
            ]
        )

