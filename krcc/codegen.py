# ================================================================
# KR32 ABI v1.0 — REGISTER AND CALLING CONVENTION
# ================================================================
#
# REGISTER ROLES:
#
#   R0        = Hardwired ZERO register
#
#   R1-R4     = Argument registers (arg0..arg3)
#               Also used for return values (R1-R4)
#               Caller-saved / volatile
#
#   R5-R11    = General-purpose working registers
#               Callee-saved / preserved
#
#   R12       = General-purpose working register
#               Callee-saved / preserved
#
#   R13       = SP (Stack Pointer)
#   R14       = FP (Frame Pointer)
#   R15       = LR (Link Register)
#
# CALLING CONVENTION:
#
#   1. Arguments 0-3 are passed in R1-R4.
#   2. Additional arguments are passed on the stack.
#   3. Return values are returned in R1-R4.
#   4. R1-R4 may be modified by the callee.
#   5. R5-R12 must be preserved by the callee.
#      Save only registers actually modified.
#   6. SP must be restored before returning.
#   7. FP must be preserved by the callee.
#   8. LR must be preserved across nested function calls.
#      A leaf function need not save LR if it does not overwrite it.
#   9. Stack grows downward (towards lower addresses).
#  10. PUSH: SP = SP - 4, then MEM[SP] = value.
#  11. POP:  value = MEM[SP], then SP = SP + 4.
#
# VOLATILE REGISTERS:
#   R1-R4
#
# NON-VOLATILE REGISTERS:
#   R5-R12, R14
#
# SPECIAL:
#   R0 = ZERO, R13 = SP, R15 = LR
#
# ================================================================

# Raised when the AST contains something that our
# current KRCC code generator cannot translate.
class CodegenError(Exception):
    pass


class CodeGenerator:
    def __init__(self):
        # Assembly instructions are accumulated here.
        self.output = []
        self.string_data = []
        #label generator counter for unique labels
        self.label_counter = 0
        #set up the register allocator for temporary registers
        self.registers = RegisterAllocator()

    def emit(self, instruction, comment=None):
        if comment:
            instruction = f"{instruction:<36} ; {comment}"
        self.output.append(instruction)

    # get a new unique label with the given prefix
    def new_label(self, prefix):
        label = f"{prefix}_{self.label_counter}"
        self.label_counter += 1
        return label

    
    def generate(self, ast):
        self.output = []
        self.string_data = []
        self.label_counter = 0

        if not isinstance(ast, TranslationUnit):
            raise CodegenError("Expected a TranslationUnit AST")
        # Check that the program defines a main() function 
        # and that it has the correct signature.
        if not any(f.name == "main" for f in ast.functions):
            raise CodegenError("Program must define main()")

        # Check that all functions have int return type 
        for function in ast.functions:
            if function.return_type != "int":
                raise CodegenError(
                    f"Only int return type is supported: {function.name}"
                )

        self.emit("; Generated by KRCC")
        self.emit("")
        self.emit(".ORG 0x00043000")
        self.emit('#include "tarfs/lib/libc.inc"')
        self.emit("")

        for function in ast.functions:
            self.generate_function(function)
            self.emit("")

        self.output.extend(self.string_data)
        return "\n".join(self.output) + "\n"
    # here we emit the function parameters to the stack frame, 
    # as they are passed in registers R1-R4, we need to store 
    # them in the stack frame
    def generate_parameters(self, function):

        if len(function.parameters) > 4:
            raise CodegenError(
                "Currently only 4 register parameters are supported"
            )

        for index, parameter in enumerate(function.parameters):

            if not hasattr(parameter, "symbol"):
                raise CodegenError(
                    f"Parameter '{parameter.name}' has no semantic symbol"
                )

            register = f"R{index + 1}"
            offset = parameter.symbol.stack_offset
            # generate code like "STW R1 [FP -4]" and so on
            # to store the parameter in the stack frame
            self.emit(
                f"    STW {register} [FP {offset:+d}]",
                f"store parameter '{parameter.name}'"
            )


    def generate_function(self, function):
        """
        Standard KR32 function frame.

        Entry:
            SP = valid stack pointer supplied by caller
            LR = return address

        Frame:
            Saved LR and FP
            Saved R5-R12
            FP points to the saved R12 slot
            [FP - 4] = local variable 1
            [FP - 8] = local variable 2
        """

        # Reset register allocation for this function.
        self.registers.reset()

        self.current_function = function

        self.emit(f"{function.name}:")

        # Save return address and caller's frame pointer.
        self.emit("    PUSH LR", "save return address")
        self.emit("    PUSH FP", "save caller's frame pointer")

        # Preserve all callee-saved working registers.
        #
        # We initially save all R5-R12.
        # Later we can optimise this to save only used registers.
        for register in self.registers.GENERAL_REGISTERS:
            self.emit(
                f"    PUSH {register}",
                f"preserve caller's {register}"
            )

        # Establish frame pointer after saving registers.
        self.emit("    MOV FP SP", "set this function's frame pointer")

        self.emit(
            f"    SUB SP SP {function.frame_size}",
            f"reserve {function.frame_size} bytes for function frame"
        )

        # Store incoming parameters in their stack-frame slots.
        self.generate_parameters(function)

        self.return_generated = False

        for statement in function.body:
            self.generate_statement(statement)

        if not self.return_generated:
            self.emit("    LI R1 0", "default return value")
            self.generate_epilogue()


    def generate_epilogue(self):

        # Discard local variables and temporary stack allocations.
        self.emit("    MOV SP FP", "discard local stack frame")

        # Restore callee-saved registers in reverse order.
        for register in reversed(self.registers.GENERAL_REGISTERS):
            self.emit(
                f"    POP {register}",
                f"restore caller's {register}"
            )

        # Restore caller's frame pointer and return address.
        self.emit("    POP FP", "restore caller's frame pointer")
        self.emit("    POP LR", "restore return address")
        self.emit("    RET", "return to caller")

    def generate_statement(self, statement):

        if isinstance(statement, VariableDeclaration):
            # Storage was allocated in the function frame.
            # No runtime instruction is required here.
            return

        if isinstance(statement, Assignment):
            self.generate_assignment(statement)
            return

        if isinstance(statement, Return):
            self.generate_return(statement)
            return

        if isinstance(statement, Print):
            self.generate_print(statement)
            return

        if isinstance(statement, While):
            self.generate_while(statement)
            return

        if isinstance(statement, DoWhile):
            self.generate_do_while(statement)
            return

        raise CodegenError(
            f"Unsupported statement: {type(statement).__name__}"
        )

    def generate_assignment(self, statement):
        if not hasattr(statement, "symbol"):
            raise CodegenError(
                f"Assignment '{statement.name}' has no semantic symbol"
            )

        symbol = statement.symbol
        offset = symbol.stack_offset

        self.generate_expression(statement.value, "R1")
        self.emit(
            f"    STW R1 [FP {offset:+d}]",
            f"store value in local variable '{statement.name}'",
        )

    def generate_expression(self, expression, target="R1"):

        # print(
        #     "EXPR DEBUG:",
        #     repr(expression),
        #     type(expression),
        #     isinstance(expression, Variable),
        #     isinstance(expression, IntLiteral)
        # )

        if isinstance(expression, IntLiteral):
            self.emit(
                f"    LI {target} {expression.value}",
                f"load integer literal {expression.value}",
            )
            return

        if isinstance(expression, Variable):
            if not hasattr(expression, "symbol"):
                raise CodegenError(
                    f"Variable '{expression.name}' has no semantic symbol"
                )

            offset = expression.symbol.stack_offset
            self.emit(
                f"    LDW {target} [FP {offset:+d}]",
                f"load local variable '{expression.name}'",
            )
            return


        if isinstance(expression, BinaryExpression):

            # Map C operators to KR32 instructions.
            operator_map = {
                "+": "ADD",
                "*": "MUL",
            }

            instruction = operator_map.get(expression.operator)

            if instruction is None:
                raise CodegenError(
                    f"Unsupported binary operator: {expression.operator}"
                )

            # -------------------------------------------------
            # Step 1: Allocate a temporary register.
            #
            # This register will hold the left operand.
            # -------------------------------------------------

            try:
                left_register = self.registers.allocate()

            except RegisterAllocationError as error:
                raise CodegenError(str(error)) from error

            try:

                # Evaluate left operand into our temporary register.
                self.generate_expression(
                    expression.left,
                    left_register
                )

                # -------------------------------------------------
                # Step 2: Evaluate the right operand.
                #
                # R1 is used as the result register.
                # The left operand remains safe in left_register.
                # -------------------------------------------------

                self.generate_expression(
                    expression.right,
                    "R1"
                )

                # -------------------------------------------------
                # Step 3: Perform the operation.
                #
                # left_register = left_register OP R1
                # -------------------------------------------------

                self.emit(
                    f"    {instruction} {left_register} "
                    f"{left_register} R1",
                    f"calculate {expression.operator} expression"
                )

                # -------------------------------------------------
                # Step 4: Move the result to the requested target.
                # -------------------------------------------------

                if target != left_register:
                    self.emit(
                        f"    MOV {target} {left_register}",
                        "move result to target register"
                    )

            finally:
                # Release the temporary register.
                # It can now be reused by another expression.
                self.registers.release(left_register)

            return

        # -------------------------------------------------
        # Function call
        #
        # Example:
        #     calculate(10, 20)
        #
        # Generate the call and leave its return value
        # in the requested target register.
        # -------------------------------------------------

        if isinstance(expression, CallExpression):
            self.generate_call(expression, target)
            return

        raise CodegenError(
            f"Unsupported expression: {type(expression).__name__}"
        )


    def generate_return(self, statement):

        self.generate_expression(statement.value)

        self.generate_epilogue()

        self.return_generated = True


    def generate_call(self, expression, target="R1"):
        """
        Generate code for a function call.

        KR32 ABI:
            R1-R4 = first four arguments
            R1    = return value

        Arguments are evaluated and temporarily pushed
        onto the stack so that evaluating later arguments
        cannot overwrite earlier ones.

        Example:
            calculate(10, 20)

        Generates:
            LI R1 10
            PUSH R1
            LI R1 20
            PUSH R1
            LDW R1 [SP + 4]
            LDW R2 [SP]
            BL calculate
            ADD SP SP 8
        """

        arguments = expression.arguments
        count = len(arguments)

        # Currently only register arguments R1-R4 are supported.
        if count > 4:
            raise CodegenError(
                "Currently only 4 function arguments are supported"
            )

        # -------------------------------------------------
        # Step 1: Evaluate each argument and save it.
        #
        # We push arguments in source order.
        # This protects earlier arguments while evaluating
        # subsequent expressions.
        # -------------------------------------------------

        for argument in arguments:
            self.generate_expression(argument, "R1")

            self.emit(
                "    PUSH R1",
                "save function argument on stack"
            )

        # -------------------------------------------------
        # Step 2: Load arguments into ABI registers.
        #
        # Because the stack grows downward, the first
        # argument is deepest in the temporary stack area.
        #
        # Example with two arguments:
        #
        #   [SP + 4] = first argument
        #   [SP]     = second argument
        # -------------------------------------------------

        for index in range(count):

            register = f"R{index + 1}"
            offset = (count - 1 - index) * 4

            self.emit(
                f"    LDW {register} [SP + {offset}]",
                f"pass argument {index + 1} in {register}"
            )

        # -------------------------------------------------
        # Step 3: Call the function.
        #
        # BL stores the return address in LR and transfers
        # execution to the function label.
        #
        # The function returns its result in R1.
        # -------------------------------------------------

        self.emit(
            f"    BL {expression.name}",
            f"call function '{expression.name}'"
        )

        # -------------------------------------------------
        # Step 4: Release temporary argument storage.
        #
        # The callee has returned, so these stack slots
        # are no longer needed.
        # -------------------------------------------------

        if count:
            self.emit(
                f"    ADD SP SP {count * 4}",
                "release temporary function arguments"
            )

        # -------------------------------------------------
        # Step 5: Move the return value if necessary.
        #
        # The ABI returns values in R1.
        # The expression may have requested another target.
        # -------------------------------------------------

        if target != "R1":
            self.emit(
                f"    MOV {target} R1",
                "move function result to target register"
            )


    
    def generate_print(self, statement):
        value = statement.format_string.value

        if not value.isascii():
            raise CodegenError(
                "printf string literals must contain ASCII text"
            )

        arguments = statement.arguments

        # Initial variadic ABI: R2-R12 = up to 11 arguments.
        if len(arguments) > 11:
            raise CodegenError(
                "printf currently supports up to 11 arguments"
            )

        label = f"printf_string_{len(self.string_data)}"

        # Evaluate each argument and temporarily push its result.
        # This prevents later expressions from overwriting earlier ones.
        for argument in arguments:
            self.generate_expression(argument, "R1")
            self.emit("    PUSH R1", "save printf argument on stack")

        # Load arguments into R2-R12.
        # Arguments were pushed in order, so the first is deepest.
        count = len(arguments)

        for i in range(count):
            register = f"R{i + 2}"
            offset = (count - 1 - i) * 4
            self.emit(
                f"    LDW {register} [SP + {offset}]",
                f"pass printf argument in {register}",
            )

        # Format string is always the first argument in R1.
        self.emit(f"    LI R1 {label}", "pass printf format string")
        self.emit("    BL printf", "call runtime printf")

        # Release temporary argument storage.
        if count:
            self.emit(
                f"    ADD SP SP {count * 4}",
                "release temporary printf arguments",
            )

        self.string_data.extend([
            "; printf format string",
            f"{label}:",
            f"    .ASCIIZ {value!r}",
        ])


    # while tests the condition before executing the body, so it may not execute at all.
    def generate_while(self, statement):
        start = self.new_label("while_start")
        body = self.new_label("while_body")
        end = self.new_label("while_end")

        self.emit(f"{start}:")

        self.generate_condition(statement.condition,body, end)

        self.emit(f"{body}:")

        for child in statement.body:
            self.generate_statement(child)

        self.emit(f"    B {start}", "repeat the while condition")

        self.emit(f"{end}:")

    # do-while tests after executing the body, so it always executes at least once.
    def generate_do_while(self, statement):
        body = self.new_label("do_body")
        end = self.new_label("do_end")

        self.emit(f"{body}:")

        for child in statement.body:
            self.generate_statement(child)

        self.generate_condition(statement.condition, body, end)

        self.emit(f"{end}:")

    def generate_condition(self, expression, true_label, false_label):

        # ------------------------------------------------
        # Case 1: Comparison expression
        # Example: x < 255
        # ------------------------------------------------
        if isinstance(expression, BinaryExpression):

            op = expression.operator

            branch_map = {
                "<":  "BLT",
                "<=": "BLE",
                ">":  "BGT",
                ">=": "BGE",
                "==": "BEQ",
                "!=": "BNE",
            }

            if op not in branch_map:
                raise CodegenError(
                    f"Unsupported condition operator: {op}"
                )

            # Evaluate left and right operands
            self.generate_expression(expression.left, "R1")
            self.generate_expression(expression.right, "R2")

            # Compare R1 with R2
            self.emit(
                "    CMP R1 R2",
                f"compare operands for condition '{op}'",
            )

            # Branch according to comparison result
            branch_true = branch_map[op]
            self.emit(
                f"    {branch_true} {true_label}",
                "enter loop body when condition is true",
            )
            self.emit(f"    B {false_label}", "exit loop when condition is false")

            return

        # ------------------------------------------------
        # Case 2: Simple expression
        # Example: while (1)
        # ------------------------------------------------

        self.generate_expression(expression, "R1")

        # Compare expression against zero
        self.emit("    CMP R1 R0", "check whether condition is nonzero")

        # Non-zero = true
        self.emit(f"    BNE {true_label}", "enter loop body when condition is true")

        # Zero = false
        self.emit(f"    B {false_label}", "exit loop when condition is false")

        
